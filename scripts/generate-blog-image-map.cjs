/**
 * Build src/data/blogImageMap.ts — maps each blog post slug to a real, relevant
 * catalog image. Blog posts are product reviews; the product name is the title
 * prefix before "Review". We match it to the closest catalog product by token
 * overlap and use that product's image. Posts with no good match are omitted
 * (getBlogImage falls back to a category image).
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');

const STOP = new Set(['the','a','an','and','or','for','with','of','in','to','pcs','pc','piece','pieces','set','new','pack','1','2','3','4','5','6','review','buying','guide','pakistan','2024','2025','2026','price','online','best','complete','in']);
const norm = s => (s||'').toLowerCase().replace(/&amp;/g,' ').replace(/[^a-z0-9 ]/g,' ').split(/\s+/).filter(w => w.length>2 && !STOP.has(w));

// catalog products
const prods = JSON.parse(fs.readFileSync(path.join(ROOT,'all_products_details.json'),'utf8'))
  .filter(p => p.image);
const prodTokens = prods.map(p => ({ image: p.image, slug: p.slug, toks: new Set(norm(p.title)) }));

// gather blog {slug,title} from both data files
const raw = fs.readFileSync(path.join(ROOT,'src/data/generatedBlogData.ts'),'utf8')
          + fs.readFileSync(path.join(ROOT,'src/data/blogData.ts'),'utf8');
const posts = [...raw.matchAll(/"?slug"?:\s*"([^"]+)"\s*,\s*"?title"?:\s*"([^"]+)"/g)]
  .map(m => ({ slug: m[1], title: m[2] }));

const map = {};
let matched = 0;
for (const post of posts) {
  if (map[post.slug]) continue;
  const name = post.title.split(/\s+review\b|:/i)[0];      // product name before "Review"/colon
  const toks = norm(name);
  if (!toks.length) continue;
  let best = null, bestScore = 0;
  for (const p of prodTokens) {
    let score = 0;
    for (const t of toks) if (p.toks.has(t)) score++;
    if (score > bestScore) { bestScore = score; best = p; }
  }
  // require a meaningful overlap (>=2 tokens, or >=50% of a short name)
  if (best && (bestScore >= 2 || (bestScore >= 1 && toks.length <= 2))) {
    map[post.slug] = best.image;
    matched++;
  }
}

const out = `// AUTO-GENERATED by scripts/generate-blog-image-map.cjs — do not edit by hand.\n`
  + `// Maps blog post slug -> relevant catalog image (by product-name match).\n`
  + `export const blogImageMap: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT,'src/data/blogImageMap.ts'), out, 'utf8');
console.log(`blog posts: ${posts.length}  matched to product image: ${matched} (${(matched/posts.length*100).toFixed(0)}%)`);
console.log('samples:');
Object.entries(map).slice(0,6).forEach(([s,img]) => console.log('  ', s.slice(0,48), '->', img.split('/').pop()));
