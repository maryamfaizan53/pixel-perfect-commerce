/**
 * Generates src/data/blogIndex.ts – a metadata-only view of every blog post
 * (everything except the heavy `content` string). Pages that only render
 * cards / related links import this instead of the full 4 MB blog dataset.
 *
 * Run: node scripts/generate-blog-index.cjs   (also wired into `npm run build`)
 */
const esbuild = require('esbuild');
const path = require('path');
const fs = require('fs');
const os = require('os');

const ROOT = path.resolve(__dirname, '..');
const ENTRY = path.join(ROOT, 'src', 'data', 'blogData.ts');
const OUT = path.join(ROOT, 'src', 'data', 'blogIndex.ts');

(async () => {
  const tmp = path.join(os.tmpdir(), `blogdata-${Date.now()}.mjs`);
  await esbuild.build({
    entryPoints: [ENTRY],
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile: tmp,
    logLevel: 'silent',
  });

  const mod = await import('file://' + tmp.replace(/\\/g, '/'));
  fs.unlinkSync(tmp);

  const posts = mod.blogPosts || [];
  // Drop the article body and other card-irrelevant heavy fields.
  const meta = posts.map(({ content, keyTakeaways, ...rest }) => rest);

  const banner = `// AUTO-GENERATED by scripts/generate-blog-index.cjs — do not edit by hand.\n` +
    `// Metadata-only blog list (no article body). Regenerate with: node scripts/generate-blog-index.cjs\n`;

  const body = `import type { BlogPost } from './blogTypes';

export type BlogPostMeta = Omit<BlogPost, 'content'>;

export const blogIndex: BlogPostMeta[] = ${JSON.stringify(meta, null, 2)};

export const getAllBlogCategories = (): string[] =>
  Array.from(new Set(blogIndex.map((p) => p.category)));

export const getFeaturedBlogPosts = (): BlogPostMeta[] =>
  blogIndex.filter((p) => p.featured);
`;

  fs.writeFileSync(OUT, banner + body);
  console.log(`blogIndex.ts written: ${meta.length} posts, ${(fs.statSync(OUT).size / 1024).toFixed(0)} KB`);
})();
